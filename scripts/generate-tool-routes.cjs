#!/usr/bin/env node
// Derive real profile destinations; never generate review content or guess page slugs.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://banglaaiguide.com';
const slugify = value => String(value || '').trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const identity = value => String(value || '').trim().replace(/\s+/g, ' ').toLowerCase();
function attributes(tag) {
  return Object.fromEntries([...tag.matchAll(/([\w:-]+)\s*=\s*(["'])([\s\S]*?)\2/g)].map(match => [match[1].toLowerCase(), match[3]]));
}
function profileIdentity(html, route) {
  const canonicals = [...html.matchAll(/<link\b[^>]*>/gi)].map(match => attributes(match[0])).filter(attr => (attr.rel || '').toLowerCase().split(/\s+/).includes('canonical'));
  if (canonicals.length !== 1 || canonicals[0].href !== SITE + route) return null;
  const apps = [];
  function collect(value) {
    if (Array.isArray(value)) return value.forEach(collect);
    if (!value || typeof value !== 'object') return;
    const types = [].concat(value['@type'] || []);
    if (types.includes('SoftwareApplication')) apps.push(value);
    if (value['@graph']) collect(value['@graph']);
  }
  for (const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (attributes(match[1]).type !== 'application/ld+json') continue;
    try { collect(JSON.parse(match[2])); } catch (_) { /* Invalid/unrelated metadata cannot establish a profile identity. */ }
  }
  // Comparison pages with several products are not an individual profile.
  if (apps.length !== 1 || apps[0].url !== SITE + route || !apps[0].name) return null;
  return identity(apps[0].name);
}
function loadTools(root = ROOT) {
  const context = {};
  vm.runInNewContext(fs.readFileSync(path.join(root, 'js/tools-data.js'), 'utf8') + '\n;globalThis.capturedTools = tools;', context, { timeout: 1000 });
  if (!Array.isArray(context.capturedTools)) throw new Error('Tool data is not an array');
  return context.capturedTools;
}
function directDestination(tool) {
  let url;
  try { url = new URL(tool.direct_url); } catch (_) { throw new Error('Missing valid direct URL for ' + tool.name); }
  if (url.protocol !== 'https:' || url.username || url.password || !url.hostname.includes('.') || /^(www\.)?banglaaiguide\.com$/i.test(url.hostname)) {
    throw new Error('Direct fallback must be an external HTTPS product URL: ' + tool.name);
  }
  return url.href;
}
function createManifest(root = ROOT, tools = loadTools(root)) {
  const profiles = new Map();
  for (const entry of fs.readdirSync(root, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
    if (!entry.isDirectory() || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.name)) continue;
    const file = path.join(root, entry.name, 'index.html');
    if (!fs.existsSync(file)) continue;
    const route = '/' + entry.name + '/';
    const name = profileIdentity(fs.readFileSync(file, 'utf8'), route);
    if (!name) continue;
    if (profiles.has(name)) throw new Error('Ambiguous profile identity: ' + name);
    profiles.set(name, route);
  }
  const manifest = {};
  for (const tool of [...tools].sort((a, b) => slugify(a.name) < slugify(b.name) ? -1 : slugify(a.name) > slugify(b.name) ? 1 : 0)) {
    const slug = slugify(tool.name);
    if (!slug || Object.hasOwn(manifest, slug)) throw new Error('Duplicate or invalid tool slug: ' + tool.name);
    const profile = profiles.get(identity(tool.name));
    manifest[slug] = {
      slug, name: tool.name, href: profile || directDestination(tool), kind: profile ? 'profile' : 'external',
      isProfile: Boolean(profile), isExternal: !profile,
      labelBn: profile ? 'টুলের বিস্তারিত' : 'টুলের ওয়েবসাইট',
      labelEn: profile ? 'View tool profile' : 'Visit product website',
    };
  }
  return manifest;
}
function renderManifest(manifest) {
  return `// Generated by scripts/generate-tool-routes.cjs. Do not edit; no review content is generated.\n(function (root, factory) {\n  const api = factory();\n  if (typeof module === 'object' && module.exports) module.exports = api;\n  else root.bagToolRoutes = api;\n})(typeof window !== 'undefined' ? window : globalThis, function () {\n  'use strict';\n  const routes = ${JSON.stringify(manifest, null, 2)};\n  const lookup = Object.create(null);\n  const slugify = ${slugify.toString()};\n  for (const route of Object.values(routes)) {\n    Object.freeze(route);\n    for (const key of [route.slug, ...(route.isProfile ? [route.href.slice(1, -1)] : [])]) {\n      if (lookup[key] && lookup[key] !== route) throw new Error('Ambiguous tool route: ' + key);\n      lookup[key] = route;\n    }\n  }\n  function resolve(tool) {\n    const key = slugify(tool && typeof tool === 'object' ? tool.name : tool);\n    return lookup[key] || null;\n  }\n  return Object.freeze({ routes: Object.freeze(routes), resolve, slugify });\n});\n`;
}
function generate(root = ROOT) {
  const manifest = createManifest(root);
  const output = renderManifest(manifest);
  const filename = path.join(root, 'js/tool-routes.js');
  const changed = !fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== output;
  if (changed) fs.writeFileSync(filename, output, 'utf8');
  const entries = Object.values(manifest);
  console.log(`Tool routes: ${entries.filter(route => route.isProfile).length} existing profiles, ${entries.filter(route => route.isExternal).length} product-site fallbacks (${changed ? 'updated' : 'unchanged'}).`);
  return manifest;
}
module.exports = { slugify, profileIdentity, loadTools, directDestination, createManifest, renderManifest, generate };
if (require.main === module) generate();
